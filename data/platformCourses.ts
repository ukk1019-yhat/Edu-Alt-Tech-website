function getThumbnail(title: string, folder: string): string {
  const seed = encodeURIComponent((title || folder || 'course').replace(/\s+/g, '-').toLowerCase().slice(0, 50));
  return `https://picsum.photos/seed/${seed}/400/225`;
}

